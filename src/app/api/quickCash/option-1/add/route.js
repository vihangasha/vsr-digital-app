
import { NextResponse } from "next/server";
import { FieldValue } from "firebase-admin/firestore";

import { adminDb } from "@/lib/firebase/admin";
import { getCurrentUser } from "@/lib/auth/session";

export const dynamic = "force-dynamic";

const COLLECTION = "quickCash";
const CUSTOMER_COLLECTION = "customers";
const HELPER_COLLECTION = "autonum-helper";

const NIC_PATTERN = /^(\d{9}[vVxX]|\d{12})$/;
const CHQ_PATTERN = /^CH-\d{4,}$/;

const WITHHOLD_RATE = 0.10;

function clean(value) {
    return String(value ?? "").trim();
}

function round2(value) {
    return Math.round((value + Number.EPSILON) * 100) / 100;
}

function isValidDate(value) {
    if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) {
        return false;
    }

    const date = new Date(`${value}T00:00:00.000Z`);

    return (
        !Number.isNaN(date.getTime()) &&
        date.toISOString().slice(0, 10) === value
    );
}

function isMissingChqNumber(value) {
    const normalized = clean(value).toUpperCase();

    return !normalized || normalized === "N/A";
}

function incrementChqRegNo(currentNumber) {
    const match = /^CH-(\d{4,})$/.exec(currentNumber);

    if (!match) {
        throw new Error(
            "HELPER_INVALID: CHQ auto-number configuration is invalid."
        );
    }

    const digits = match[1];

    const nextValue = (BigInt(digits) + 1n)
        .toString()
        .padStart(digits.length, "0");

    return `CH-${nextValue}`;
}

function apiError(error, status, code) {
    return NextResponse.json(
        {
            success: false,
            error,
            ...(code ? { code } : {}),
        },
        { status }
    );
}

export async function POST(request) {
    try {
        // --------------------------------------------------
        // 1. Same-origin request protection
        // --------------------------------------------------

        const requestOrigin = new URL(request.url).origin;
        const origin = request.headers.get("origin");
        const fetchSite = request.headers.get("sec-fetch-site");
        const fetchMode = request.headers.get("sec-fetch-mode");

        if (
            fetchSite !== "same-origin" ||
            (origin && origin !== requestOrigin) ||
            fetchMode === "navigate"
        ) {
            return apiError("Forbidden request.", 403);
        }

        // --------------------------------------------------
        // 2. Authentication
        // --------------------------------------------------

        const currentUser = await getCurrentUser();

        if (!currentUser) {
            return apiError(
                "Unauthorized. Please log in.",
                401
            );
        }

        const updatedBy = clean(
            currentUser.uid ||
            currentUser.userID ||
            currentUser.email
        );

        if (!updatedBy) {
            return apiError(
                "Unable to identify the authenticated user.",
                401
            );
        }

        // --------------------------------------------------
        // 3. Read request body
        // --------------------------------------------------

        let body;

        try {
            body = await request.json();
        } catch {
            return apiError("Invalid request body.", 400);
        }

        // --------------------------------------------------
        // 4. This endpoint is exclusively Option 1
        // --------------------------------------------------

        const submittedOption = clean(body?.option).toLowerCase();

        if (
            submittedOption &&
            !["option1", "option-1"].includes(submittedOption)
        ) {
            return apiError(
                "This endpoint only accepts Option 1 registrations.",
                400,
                "INVALID_OPTION"
            );
        }

        // The database value is always option-1.
        const option = "option-1";

        // --------------------------------------------------
        // 5. Normalize submitted fields
        // --------------------------------------------------

        const nic = clean(body?.nic).toUpperCase();

        const bank = clean(body?.bank);
        const chequeNo = clean(body?.chequeNo);

        const dateIssued = clean(body?.dateIssued);
        const passingDate = clean(body?.passingDate);

        const submittedChqRegNo = clean(body?.chqRegNo)
            .toUpperCase();

        const writtenAmount = Number(body?.writtenAmount);

        const chqRegNoAutoGenerated =
            body?.chqRegNoAutoGenerated;

        // --------------------------------------------------
        // 6. Validate customer and CHQ registration inputs
        // --------------------------------------------------

        if (!NIC_PATTERN.test(nic)) {
            return apiError("Invalid customer NIC.", 400);
        }

        if (typeof chqRegNoAutoGenerated !== "boolean") {
            return apiError(
                "Invalid CHQ registration type. Please verify the CHQ number and try again.",
                400,
                "INVALID_CHQ_REGISTRATION_TYPE"
            );
        }

        if (!CHQ_PATTERN.test(submittedChqRegNo)) {
            return apiError(
                "A valid CHQ registration number is required.",
                400,
                "INVALID_CHQ_NUMBER"
            );
        }

        // --------------------------------------------------
        // 7. Validate cheque details
        // --------------------------------------------------

        if (!bank) {
            return apiError(
                "Issuing bank name is required.",
                400
            );
        }

        if (!chequeNo) {
            return apiError(
                "Cheque number is required.",
                400
            );
        }

        if (!isValidDate(dateIssued)) {
            return apiError(
                "A valid issued date is required.",
                400
            );
        }

        if (!isValidDate(passingDate)) {
            return apiError(
                "A valid passing date is required.",
                400
            );
        }

        if (passingDate < dateIssued) {
            return apiError(
                "Passing date cannot be before the issued date.",
                400
            );
        }

        if (
            !Number.isFinite(writtenAmount) ||
            writtenAmount <= 0 ||
            writtenAmount > 1000000000000
        ) {
            return apiError(
                "Invalid written amount.",
                400
            );
        }

        // --------------------------------------------------
        // 8. Calculate amounts on the server
        // --------------------------------------------------

        const withheldAmount = round2(
            writtenAmount * WITHHOLD_RATE
        );

        const issuedAmount = round2(
            writtenAmount - withheldAmount
        );

        // --------------------------------------------------
        // 9. Prepare Firestore references
        // --------------------------------------------------

        const recordRef = adminDb
            .collection(COLLECTION)
            .doc();

        const customerRef = adminDb
            .collection(CUSTOMER_COLLECTION)
            .doc(nic);

        const helperRef = adminDb
            .collection(HELPER_COLLECTION)
            .doc("helperID");

        let savedRecord = null;
        let assignedChqRegNo = null;
        let generatedNewChqNumber = false;

        // --------------------------------------------------
        // 10. Atomic Firestore transaction
        // --------------------------------------------------

        await adminDb.runTransaction(async (transaction) => {
            // Read customer first.
            const customerSnapshot =
                await transaction.get(customerRef);

            if (!customerSnapshot.exists) {
                throw new Error(
                    "CUSTOMER_NOT_FOUND: Customer does not exist."
                );
            }

            const customerData = customerSnapshot.data();

            const finalName = clean(customerData?.fullName);

            if (!finalName) {
                throw new Error(
                    "CUSTOMER_NAME_MISSING: Customer name is missing."
                );
            }

            const existingChqRegNo = clean(
                customerData?.chqRegNo
            ).toUpperCase();

            const customerHasChqNumber =
                !isMissingChqNumber(existingChqRegNo);

            let finalChqRegNo = "";
            let shouldAssignNewChqNumber = false;
            let nextChqRegNo = null;

            // ----------------------------------------------
            // SCENARIO 1:
            // Customer already has a CHQ registration number.
            //
            // UI signal must be false.
            // Only create the Quick Cash record.
            // ----------------------------------------------

            if (!chqRegNoAutoGenerated) {
                if (!customerHasChqNumber) {
                    throw new Error(
                        "CHQ_TYPE_MISMATCH: This customer does not have an existing CHQ number. Fetch a new number first."
                    );
                }

                if (!CHQ_PATTERN.test(existingChqRegNo)) {
                    throw new Error(
                        "CUSTOMER_CHQ_INVALID: Customer CHQ registration number is invalid."
                    );
                }

                // Reject a client value that differs from
                // the authoritative customer document.
                if (submittedChqRegNo !== existingChqRegNo) {
                    throw new Error(
                        "CHQ_NUMBER_MISMATCH: The submitted CHQ number does not match the customer's existing number."
                    );
                }

                finalChqRegNo = existingChqRegNo;

                // No customer update.
                // No helper read or update.
            }

            // ----------------------------------------------
            // SCENARIO 2:
            // Customer does not have a CHQ registration number.
            //
            // UI signal must be true.
            // Verify helper number and assign it atomically.
            // ----------------------------------------------

            else {
                if (customerHasChqNumber) {
                    throw new Error(
                        "CHQ_TYPE_MISMATCH: This customer already has a CHQ number. Use the existing customer number instead."
                    );
                }

                // Read helper only for a new assignment.
                const helperSnapshot =
                    await transaction.get(helperRef);

                if (!helperSnapshot.exists) {
                    throw new Error(
                        "HELPER_NOT_FOUND: CHQ auto-number configuration not found."
                    );
                }

                const helperData = helperSnapshot.data();

                const currentHelperNumber = clean(
                    helperData?.chqRegNo
                ).toUpperCase();

                if (!CHQ_PATTERN.test(currentHelperNumber)) {
                    throw new Error(
                        "HELPER_INVALID: CHQ auto-number configuration is invalid."
                    );
                }

                // Ensure the fetched number is still available.
                if (submittedChqRegNo !== currentHelperNumber) {
                    throw new Error(
                        "CHQ_NUMBER_STALE: This CHQ number is no longer available. Fetch the latest number and try again."
                    );
                }

                finalChqRegNo = currentHelperNumber;

                nextChqRegNo = incrementChqRegNo(
                    currentHelperNumber
                );

                shouldAssignNewChqNumber = true;
            }

            // ----------------------------------------------
            // Prepare Quick Cash record
            // ----------------------------------------------

            const record = {
                qcID: recordRef.id,

                option,

                name: finalName,
                nic,

                chqRegNo: finalChqRegNo,

                bank,
                chequeNo,

                writtenAmount,
                withheldAmount,
                issuedAmount,

                dateIssued,
                passingDate,

                updatedBy,

                createdAt: FieldValue.serverTimestamp(),
            };

            // ----------------------------------------------
            // All transaction reads are complete.
            // Perform writes.
            // ----------------------------------------------

            transaction.create(recordRef, record);

            if (shouldAssignNewChqNumber) {
                // Assign the CHQ number to the customer.
                transaction.update(customerRef, {
                    chqRegNo: finalChqRegNo,
                });

                // Advance only the CHQ helper counter.
                // Other helper fields remain untouched.
                transaction.update(helperRef, {
                    chqRegNo: nextChqRegNo,
                });

                generatedNewChqNumber = true;
            }

            savedRecord = {
                ...record,
                createdAt: new Date().toISOString(),
            };

            assignedChqRegNo = finalChqRegNo;
        });

        // --------------------------------------------------
        // 11. Success response
        // --------------------------------------------------

        return NextResponse.json(
            {
                success: true,
                message: "Quick Cash record saved successfully.",
                record: savedRecord,
                chqRegNo: assignedChqRegNo,
                newChqNumberAssigned: generatedNewChqNumber,
            },
            { status: 201 }
        );

    } catch (error) {
        const message = error?.message || "";

        const knownErrors = [
            "CUSTOMER_NOT_FOUND:",
            "CUSTOMER_NAME_MISSING:",
            "CUSTOMER_CHQ_INVALID:",
            "CHQ_TYPE_MISMATCH:",
            "CHQ_NUMBER_MISMATCH:",
            "HELPER_NOT_FOUND:",
            "HELPER_INVALID:",
            "CHQ_NUMBER_STALE:",
        ];

        const knownError = knownErrors.find((prefix) =>
            message.startsWith(prefix)
        );

        if (knownError) {
            let status = 400;

            if (message.startsWith("CUSTOMER_NOT_FOUND:")) {
                status = 404;
            } else if (
                message.startsWith("CHQ_NUMBER_STALE:")
            ) {
                status = 409;
            }

            return NextResponse.json(
                {
                    success: false,
                    error: message.slice(knownError.length).trim(),
                    code: knownError.replace(":", ""),
                },
                { status }
            );
        }

        console.error(
            "Quick Cash Option 1 registration error:",
            error
        );

        return apiError(
            "Unable to register Quick Cash record.",
            500
        );
    }
}
