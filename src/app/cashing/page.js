export default function CashingPage() {
    const [activeTab, setActiveTab] = useState("option1");
    const [bannerOpen, setBannerOpen] = useState(false);

    const [forms, setForms] = useState(initialForms);
    const [errors, setErrors] = useState({});
    const [savingOption, setSavingOption] = useState(null);

    const [notices, setNotices] = useState({
        option1: "",
        option2: "",
    });

    const [records, setRecords] = useState([]);
    const [recordsLoading, setRecordsLoading] = useState(false);
    const [recordsError, setRecordsError] = useState("");
    const [search, setSearch] = useState("");

    const heroRef = useRef(null);
    const tabsScrollRef = useRef(null);
    const settingsRef = useRef(null);
    const tabRefs = useRef({});
    const collapseTimer = useRef(null);
    const wasOpen = useRef(false);
    const [indicator, setIndicator] = useState({
        left: 0,
        top: 0,
        width: 0,
        height: 0,
        ready: false,
    });

    const today = useMemo(
        () => new Date().toLocaleDateString("en-GB"),
        []
    );

    const isView = activeTab === "view";

    const tab =
        TABS.find((item) => item.id === activeTab) || TABS[0];

    const clearCollapseTimer = useCallback(() => {
        if (collapseTimer.current) {
            clearTimeout(collapseTimer.current);
            collapseTimer.current = null;
        }
    }, []);

    // Roll the banner back up. A small delay lets the person see their choice land first.
    const closeBanner = useCallback(
        (delay = 0) => {
            clearCollapseTimer();
            if (delay > 0) {
                collapseTimer.current = setTimeout(
                    () => setBannerOpen(false),
                    delay
                );
            } else {
                setBannerOpen(false);
            }
        },
        [clearCollapseTimer]
    );

    const toggleBanner = useCallback(() => {
        clearCollapseTimer();
        setBannerOpen((previous) => !previous);
    }, [clearCollapseTimer]);

    // collapse is true only for real clicks; arrow-key browsing keeps the banner open
    const selectTab = useCallback(
        (id, collapse = false) => {
            setActiveTab(id);
            if (collapse) closeBanner(420);
        },
        [closeBanner]
    );

    useEffect(() => () => clearTimeout(collapseTimer.current), []);

    // Escape rolls the banner up
    useEffect(() => {
        if (!bannerOpen) return;
        const onKeyDown = (event) => {
            if (event.key === "Escape") setBannerOpen(false);
        };
        window.addEventListener("keydown", onKeyDown);
        return () => window.removeEventListener("keydown", onKeyDown);
    }, [bannerOpen]);

    // Focus: into the active tab on open, back to the settings button on close
    useEffect(() => {
        if (bannerOpen) {
            tabRefs.current[activeTab]?.focus({ preventScroll: true });
        } else if (
            wasOpen.current &&
            heroRef.current?.contains(document.activeElement)
        ) {
            settingsRef.current?.focus({ preventScroll: true });
        }
        wasOpen.current = bannerOpen;
        // eslint-disable-next-line react-hooks/exhaustive-deps
    }, [bannerOpen]);

    // Sliding pill behind the active tab (re-measured on resize and once fonts load)
    useLayoutEffect(() => {
        const measure = () => {
            const element = tabRefs.current[activeTab];
            if (!element) return;
            setIndicator({
                left: element.offsetLeft,
                top: element.offsetTop,
                width: element.offsetWidth,
                height: element.offsetHeight,
                ready: true,
            });
        };
        measure();

        // When the track scrolls sideways, keep the active tab centred
        const track = tabsScrollRef.current;
        const active = tabRefs.current[activeTab];
        if (track && active && track.scrollWidth > track.clientWidth) {
            track.scrollTo({
                left:
                    active.offsetLeft -
                    (track.clientWidth - active.offsetWidth) / 2,
                behavior: "smooth",
            });
        }

        window.addEventListener("resize", measure);
        document.fonts?.ready.then(measure);
        return () => window.removeEventListener("resize", measure);
    }, [activeTab]);

    // Tab track scrolling: edge-fade hints (data-scroll-start / data-scroll-end)
    // + mouse drag-to-scroll. Touch screens use native swipe scrolling.
    useEffect(() => {
        const track = tabsScrollRef.current;
        if (!track) return;

        const updateEdges = () => {
            const max = track.scrollWidth - track.clientWidth;
            track.dataset.scrollStart =
                track.scrollLeft > 4 ? "false" : "true";
            track.dataset.scrollEnd =
                max > 4 && track.scrollLeft < max - 4 ? "false" : "true";
        };
        updateEdges();
        track.addEventListener("scroll", updateEdges, { passive: true });
        window.addEventListener("resize", updateEdges);
        const observer =
            typeof ResizeObserver !== "undefined"
                ? new ResizeObserver(updateEdges)
                : null;
        observer?.observe(track);

        let startX = 0;
        let startScroll = 0;
        let dragging = false;
        let moved = false;

        const onDown = (event) => {
            if (event.pointerType !== "mouse" || event.button !== 0) return;
            if (track.scrollWidth <= track.clientWidth) return;
            dragging = true;
            moved = false;
            startX = event.clientX;
            startScroll = track.scrollLeft;
        };
        const onMove = (event) => {
            if (!dragging) return;
            const dx = event.clientX - startX;
            if (Math.abs(dx) > 5) {
                moved = true;
                track.classList.add("is-dragging");
            }
            if (moved) track.scrollLeft = startScroll - dx;
        };
        const onUp = () => {
            if (!dragging) return;
            dragging = false;
            track.classList.remove("is-dragging");
        };
        // a drag must not count as a tab click
        const onClickCapture = (event) => {
            if (moved) {
                event.preventDefault();
                event.stopPropagation();
                moved = false;
            }
        };

        track.addEventListener("pointerdown", onDown);
        window.addEventListener("pointermove", onMove);
        window.addEventListener("pointerup", onUp);
        window.addEventListener("pointercancel", onUp);
        track.addEventListener("click", onClickCapture, true);

        return () => {
            track.removeEventListener("scroll", updateEdges);
            window.removeEventListener("resize", updateEdges);
            observer?.disconnect();
            track.removeEventListener("pointerdown", onDown);
            window.removeEventListener("pointermove", onMove);
            window.removeEventListener("pointerup", onUp);
            window.removeEventListener("pointercancel", onUp);
            track.removeEventListener("click", onClickCapture, true);
        };
    }, []);

    // Arrow-key navigation across the tabs
    const handleTabKeyDown = (event) => {
        const index = TABS.findIndex((item) => item.id === activeTab);
        let next = null;
        if (event.key === "ArrowRight") next = (index + 1) % TABS.length;
        else if (event.key === "ArrowLeft")
            next = (index - 1 + TABS.length) % TABS.length;
        else if (event.key === "Home") next = 0;
        else if (event.key === "End") next = TABS.length - 1;
        if (next === null) return;
        event.preventDefault();
        selectTab(TABS[next].id);
        tabRefs.current[TABS[next].id]?.focus({ preventScroll: true });
    };

    const updateField = useCallback((optionId, field, value) => {
        setForms((previous) => ({
            ...previous,
            [optionId]: {
                ...previous[optionId],
                [field]: value,
            },
        }));

        setErrors((previous) => ({
            ...previous,
            [field]: undefined,
        }));
    }, []);

    const resetForm = useCallback((optionId) => {
        setForms((previous) => ({
            ...previous,
            [optionId]: createEmptyForm(optionId),
        }));

        setErrors({});
        setNotices((previous) => ({
            ...previous,
            [optionId]: "",
        }));
    }, []);

    const refreshRecords = useCallback(async () => {
        setRecordsLoading(true);
        setRecordsError("");

        try {
            const result = await fetchRecords();
            setRecords(result);
        } catch (error) {
            setRecordsError(
                error.message || "Unable to fetch records."
            );
        } finally {
            setRecordsLoading(false);
        }
    }, []);

    useEffect(() => {
        refreshRecords();
    }, [refreshRecords]);

    const submitForm = async (event, optionId) => {
        event.preventDefault();

        const form = forms[optionId];
        const nextErrors =
            optionId === "option2"
                ? validateOption2(form)
                : validate(form, optionId);

        if (Object.values(nextErrors).some(Boolean)) {
            setErrors(nextErrors);
            return;
        }

        setErrors({});
        setSavingOption(optionId);

        const writtenAmount =
            optionId === "option2"
                ? calculateOption2(form.issuedAmount).written
                : Number(form.writtenAmount);

        const { withheld, exchanged } =
            optionId === "option2"
                ? calculateOption2(form.issuedAmount)
                : calculate(writtenAmount, optionId);

        const record = {
            option: optionId,
            name: form.name.trim(),
            nic: form.nic.trim(),
            chqRegNo: form.chqRegNo?.trim() || "",
            chqRegNoAutoGenerated:
                form.chqRegNoAutoGenerated === true,
            bank: form.bank.trim(),
            chequeNo: form.chequeNo.trim(),
            dateIssued: form.dateIssued,
            passingDate: form.passingDate,
            ...(optionId === "option2"
                ? { issuedAmount: Number(form.issuedAmount) }
                : {}),
            writtenAmount,
            amountExchanged: exchanged,
            amountWithheld: withheld,
            createdAt: new Date().toISOString(),
        };

        try {
            const saved = await saveRecord(record);

            setRecords((previous) => [saved, ...previous]);

            setForms((previous) => ({
                ...previous,
                [optionId]: createEmptyForm(optionId),
            }));

            setNotices((previous) => ({
                ...previous,
                [optionId]:
                    optionId === "option2"
                        ? `Cheque ${record.chequeNo} saved for ${record.name}.\n` +
                        `Issued ${money(record.issuedAmount)}. ` +
                        `Written ${money(record.writtenAmount)}.`
                        : `Cheque ${record.chequeNo} saved for ${record.name}.\n` +
                        `Exchanged ${money(exchanged)}. ` +
                        `Withheld ${money(withheld)}.`,
            }));

        } catch (error) {
            setNotices((previous) => ({
                ...previous,
                [optionId]:
                    error.message || "Unable to save cheque.",
            }));

        } finally {
            setSavingOption(null);
        }
    };

    const visibleRecords = useMemo(() => {
        const query = search.trim().toLowerCase();

        if (!query) return records;

        return records.filter((record) =>
            [
                record.name,
                record.nic,
                record.chqRegNo,
                record.chequeNo,
                record.option,
            ]
                .filter(Boolean)
                .some((value) =>
                    String(value).toLowerCase().includes(query)
                )
        );
    }, [records, search]);

    const totals = useMemo(
        () =>
            visibleRecords.reduce(
                (sum, record) => ({
                    written:
                        sum.written +
                        Number(record.writtenAmount || 0),
                    exchanged:
                        sum.exchanged +
                        Number(record.amountExchanged || 0),
                    withheld:
                        sum.withheld +
                        Number(record.withheldAmount || 0),
                }),
                {
                    written: 0,
                    exchanged: 0,
                    withheld: 0,
                }
            ),
        [visibleRecords]
    );

    const VIEW_COLUMNS = [
        {
            key: "option",
            label: "Option",
            text: (r) => OPTION_LABEL[r.option] || r.option,
            badge: true,
        },
        {
            key: "name",
            label: "Name",
            text: (r) => r.name,
        },
        {
            key: "nic",
            label: "NIC",
            text: (r) => r.nic,
        },
        {
            key: "chequeNo",
            label: "Cheque No.",
            text: (r) => r.chequeNo,
        },
        {
            key: "dateIssued",
            label: "Date issued",
            text: (r) => formatDate(r.dateIssued),
        },
        {
            key: "writtenAmount",
            label: "Written amount",
            text: (r) => money(r.writtenAmount),
            num: true,
        },
        {
            key: "passingDate",
            label: "Passing date",
            text: (r) => formatDate(r.passingDate),
        },
        {
            key: "amountExchanged",
            label: "Amount Exchanged",
            text: (r) => money(r.amountExchanged),
            num: true,
        },
        {
            key: "amountWithheld",
            label: "Amount Withheld",
            text: (r) => money(r.amountWithheld),
            num: true,
        },
    ];

    return (
        <main className="min-h-screen bg-[#171717]">
            <div className="home-navbar-fixed">
                <Navbar />
            </div>

            <div className="home-page cashing-page">
                <div
                    className={`cashing-scrim${bannerOpen ? " is-visible" : ""
                        }`}
                    onClick={() => closeBanner()}
                    aria-hidden="true"
                />

                <section
                    ref={heroRef}
                    className={`home-hero cashing-hero ${bannerOpen ? "is-open" : "is-collapsed"
                        }`}
                >
                    <div className="home-hero__glow" />

                    <div className="home-hero__stripes">
                        {Array.from({ length: 12 }).map((_, index) => (
                            <span
                                key={index}
                                className={`home-hero__stripe home-hero__stripe--${index + 1
                                    }`}
                            />
                        ))}
                    </div>

                    <div
                        className="cashing-hero__content"
                        id="cashing-hero-panel"
                    >
                        <div className="cashing-hero__top">
                            <div className="cashing-hero__heading">
                                <h1 className="cashing-hero__title">
                                    CASHING
                                </h1>

                                <span className="cashing-hero__meta">
                                    {today}
                                </span>
                            </div>

                            <button
                                type="button"
                                className="cashing-hero__btn cashing-hero__btn--icon"
                                onClick={() => closeBanner()}
                                aria-label="Roll up banner"
                                title="Roll up"
                            >
                                <ChevronUp
                                    size={18}
                                    strokeWidth={2.3}
                                />
                            </button>
                        </div>

                        <div className="cashing-tabs">
                            <div
                                ref={tabsScrollRef}
                                className="cashing-tabs__scroll"
                                role="tablist"
                                aria-label="Cashing sections"
                                onKeyDown={handleTabKeyDown}
                            >
                                <span
                                    className={`cashing-tabs__indicator${indicator.ready ? " is-ready" : ""}`}
                                    style={{
                                        width: indicator.width,
                                        height: indicator.height,
                                        transform: `translate(${indicator.left}px, ${indicator.top}px)`,
                                    }}
                                    aria-hidden="true"
                                />

                                {TABS.map((item) => (
                                    <button
                                        key={item.id}
                                        ref={(element) => {
                                            tabRefs.current[item.id] =
                                                element;
                                        }}
                                        type="button"
                                        role="tab"
                                        id={`tab-${item.id}`}
                                        aria-selected={
                                            activeTab === item.id
                                        }
                                        aria-controls="cashing-panel"
                                        tabIndex={
                                            activeTab === item.id ? 0 : -1
                                        }
                                        className={`cashing-tabs__btn${activeTab === item.id
                                            ? " is-active"
                                            : ""
                                            }`}
                                        onClick={() =>
                                            selectTab(item.id, true)
                                        }
                                    >
                                        {item.label}
                                    </button>
                                ))}
                            </div>
                        </div>
                    </div>

                    <div className="cashing-hero__bar">
                        <h1 className="cashing-hero__bar-title">
                            CASHING
                        </h1>

                        <span
                            key={activeTab}
                            className="cashing-hero__bar-tab"
                            aria-live="polite"
                        >
                            {tab.label}
                        </span>

                        <button
                            ref={settingsRef}
                            type="button"
                            className="cashing-hero__settings"
                            onClick={toggleBanner}
                            aria-label="Open cashing sections"
                            aria-expanded={bannerOpen}
                            aria-controls="cashing-hero-panel"
                            title="Settings"
                        >
                            <CogIcon size={20} />
                        </button>
                    </div>
                </section>

                <section className="cashing-content">
                    <div className="cashing-surface">
                        <SurfaceDecor />

                        <header className="cashing-header">
                            <h2>
                                {isView
                                    ? "All cheques"
                                    : `${tab.label} cheque`}
                            </h2>

                            <p>
                                {isView
                                    ? "Every cheque recorded under Option 1 and Option 2."
                                    : "Fill in the cheque details. The exchanged and withheld amounts are worked out from the written amount."}
                            </p>
                        </header>

                        <div
                            key={activeTab}
                            id="cashing-panel"
                            className="cashing-panel"
                            role="tabpanel"
                            aria-labelledby={`tab-${activeTab}`}
                        >
                            {!isView ? (
                                <section className="cashing-section cashing-section--last">
                                    <div className="cashing-section__intro">
                                        <h3>Cheque details</h3>

                                        <p>
                                            {(
                                                WITHHOLD_RATE[activeTab] ??
                                                0
                                            ) * 100}
                                            % of the written amount is
                                            withheld; the rest is exchanged.
                                        </p>
                                    </div>

                                    <div className="cashing-section__body">
                                        <CashingForm
                                            optionId={activeTab}
                                            form={forms[activeTab]}
                                            errors={errors}
                                            saving={
                                                savingOption === activeTab
                                            }
                                            notice={notices[activeTab]}
                                            onChange={(field, value) =>
                                                updateField(
                                                    activeTab,
                                                    field,
                                                    value
                                                )
                                            }
                                            onSubmit={(event) =>
                                                submitForm(
                                                    event,
                                                    activeTab
                                                )
                                            }
                                            onReset={() =>
                                                resetForm(activeTab)
                                            }
                                        />
                                    </div>
                                </section>
                            ) : (
                                <section className="cashing-view">
                                    <div className="home-card__head cashing-view__head">
                                        <div>
                                            <h2>
                                                Cheque Records{" "}
                                                <span className="cashing-count">
                                                    {recordsLoading
                                                        ? "…"
                                                        : visibleRecords.length}
                                                </span>
                                            </h2>

                                            <p>
                                                Every cheque saved under
                                                Option 1 and Option 2, with
                                                its exchanged and withheld
                                                amounts.
                                            </p>
                                        </div>

                                        <button
                                            type="button"
                                            className="cashing-btn cashing-btn--light cashing-refresh"
                                            onClick={refreshRecords}
                                            disabled={recordsLoading}
                                        >
                                            {recordsLoading ? (
                                                <>
                                                    <span
                                                        className="cashing-spinner"
                                                        aria-hidden="true"
                                                    />
                                                    Refreshing
                                                </>
                                            ) : (
                                                "Refresh"
                                            )}
                                        </button>
                                    </div>

                                    <div className="home-search">
                                        <Search
                                            size={16}
                                            className="home-search__icon"
                                            aria-hidden="true"
                                        />

                                        <input
                                            type="search"
                                            value={search}
                                            onChange={(e) =>
                                                setSearch(e.target.value)
                                            }
                                            placeholder="Search cheques"
                                            aria-label="Search cheques"
                                            autoComplete="off"
                                        />
                                    </div>

                                    <div className="home-table-wrap">
                                        <table className="home-table cashing-table">
                                            <thead>
                                                <tr>
                                                    {VIEW_COLUMNS.map((c) => (
                                                        <th
                                                            key={c.key}
                                                            className={
                                                                c.num
                                                                    ? "is-num"
                                                                    : undefined
                                                            }
                                                        >
                                                            {c.label}
                                                        </th>
                                                    ))}
                                                </tr>
                                            </thead>

                                            <tbody>
                                                {visibleRecords.map(
                                                    (record, index) => (
                                                        <tr
                                                            key={
                                                                record.id ??
                                                                index
                                                            }
                                                        >
                                                            {VIEW_COLUMNS.map(
                                                                (c) => {
                                                                    const value =
                                                                        c.text(
                                                                            record
                                                                        ) || "-";

                                                                    return (
                                                                        <td
                                                                            key={
                                                                                c.key
                                                                            }
                                                                            className={
                                                                                c.num
                                                                                    ? "is-num"
                                                                                    : undefined
                                                                            }
                                                                        >
                                                                            {c.badge ? (
                                                                                <span className="home-badge">
                                                                                    {value}
                                                                                </span>
                                                                            ) : (
                                                                                value
                                                                            )}
                                                                        </td>
                                                                    );
                                                                }
                                                            )}
                                                        </tr>
                                                    )
                                                )}
                                            </tbody>

                                            {visibleRecords.length > 0 && (
                                                <tfoot>
                                                    <tr>
                                                        <td colSpan={5}>
                                                            Total
                                                        </td>

                                                        <td className="is-num">
                                                            {money(
                                                                totals.written
                                                            )}
                                                        </td>

                                                        <td />

                                                        <td className="is-num">
                                                            {money(
                                                                totals.exchanged
                                                            )}
                                                        </td>

                                                        <td className="is-num">
                                                            {money(
                                                                totals.withheld
                                                            )}
                                                        </td>
                                                    </tr>
                                                </tfoot>
                                            )}
                                        </table>

                                        {recordsLoading ? (
                                            <p className="home-empty">
                                                Loading records...
                                            </p>
                                        ) : recordsError ? (
                                            <p className="home-empty">
                                                {recordsError}
                                            </p>
                                        ) : records.length === 0 ? (
                                            <p className="home-empty">
                                                No cheques recorded yet. Add
                                                one under Option 1 or Option 2.
                                            </p>
                                        ) : visibleRecords.length === 0 ? (
                                            <p className="home-empty">
                                                No cheques match your search.
                                                Clear it to see all records.
                                            </p>
                                        ) : null}
                                    </div>
                                </section>
                            )}
                        </div>
                    </div>
                </section>
            </div>
        </main>
    );
}