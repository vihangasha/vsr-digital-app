async function saveRecord(record) {
    // Option 1: Keep the existing working API integration unchanged.
    if (record.option === "option1") {
        const response = await fetch(
            "/api/quickCash/option-1/add",
            {
                method: "POST",
                headers: {
                    "Content-Type": "application/json",
                    Accept: "application/json",
                },
                credentials: "include",
                body: JSON.stringify(record),
            }
        );

        const data = await response.json().catch(() => ({}));

        if (!response.ok || !data.success) {
            throw new Error(
                data.error || "Unable to save Quick Cash record."
            );
        }

        return {
            ...data.record,
            id: data.record?.qcID,
        };
    }

    // Option 2: Save through its dedicated POST API.
    if (record.option === "option2") {
        const response = await fetch(
            "/api/quickCash/option-2/add",
            {
                method: "POST",
                headers: {
                    "Content-Type": "application/json",
                    Accept: "application/json",
                },
                credentials: "include",
                body: JSON.stringify(record),
            }
        );

        const data = await response.json().catch(() => ({}));

        if (!response.ok || !data.success) {
            throw new Error(
                data.error || "Unable to save Option 2 Quick Cash record."
            );
        }

        return {
            ...data.record,
            option: "option2",
            id: data.record?.qcID,
        };
    }

    throw new Error("Invalid Quick Cash option.");
}

