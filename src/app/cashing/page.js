const money = (value) =>
    `Rs. ${Number(value ?? 0).toLocaleString("en-LK", {
        minimumFractionDigits: 2,
        maximumFractionDigits: 2,
    })}`;

const round2 = (value) => Math.round(value * 100) / 100;

function calculate(writtenAmount, optionId) {
    const written = Number(writtenAmount);

    if (!Number.isFinite(written) || written <= 0) {
        return {
            withheld: 0,
            exchanged: 0,
        };
    }

    const withheld = round2(
        written * (WITHHOLD_RATE[optionId] ?? 0)
    );

    return {
        withheld,
        exchanged: round2(written - withheld),
    };
}

function calculateOption2(issuedAmount) {
    const issued = Number(issuedAmount);

    if (!Number.isFinite(issued) || issued <= 0) {
        return {
            written: 0,
            withheld: 0,
            exchanged: 0,
        };
    }

    const written = round2(issued * 1.10);

    // Profit of the deal = the 10% added on top of the issued amount.
    const withheld = round2(written - issued);

    return {
        written,
        withheld,
        exchanged: round2(written - withheld),
    };
}

function formatDate(value) {
    if (!value) return "-";

    const date = new Date(`${value}T00:00:00`);

    if (Number.isNaN(date.getTime())) return value;

    return date.toLocaleDateString("en-GB");
}

function getTodayISO() {
    const now = new Date();
    const offset = now.getTimezoneOffset() * 60000;

    return new Date(now.getTime() - offset)
        .toISOString()
        .slice(0, 10);
}

// Old NIC (9 digits + V/X) or new NIC (12 digits)
const NIC_PATTERN = /^(\d{9}[vVxX]|\d{12})$/;

function validate(form, optionId) {
    const errors = {};

    if (!form.name.trim()) {
        errors.name = "Enter the customer's name.";
    }

    if (!form.nic.trim()) {
        errors.nic = "Enter the NIC number.";
    } else if (!NIC_PATTERN.test(form.nic.trim())) {
        errors.nic = "Use 9 digits and V/X, or 12 digits.";
    }

    if (!form.chequeNo.trim()) {
        errors.chequeNo = "Enter the cheque number.";
    }

    if (!form.dateIssued) {
        errors.dateIssued = "Choose the date issued.";
    }

    if (optionId === "option2") {
        const issued = Number(form.issuedAmount);

        if (
            !form.issuedAmount ||
            !Number.isFinite(issued) ||
            issued <= 0
        ) {
            errors.issuedAmount =
                "Enter an issued amount greater than zero.";
        }
    } else {
        const written = Number(form.writtenAmount);

        if (
            !form.writtenAmount ||
            !Number.isFinite(written) ||
            written <= 0
        ) {
            errors.writtenAmount = "Enter an amount greater than zero.";
        }
    }

    if (!form.passingDate) {
        errors.passingDate = "Choose the passing date.";
    } else if (
        form.dateIssued &&
        form.passingDate < form.dateIssued
    ) {
        errors.passingDate = "Passing date can't be before the date issued.";
    }

    return errors;
}

function validateOption2(form) {
    const errors = {};

    if (!form.nic.trim()) {
        errors.nic = "Enter the NIC number.";
    } else if (!NIC_PATTERN.test(form.nic.trim())) {
        errors.nic = "Use 9 digits and V/X, or 12 digits.";
    }

    if (!form.name.trim()) {
        errors.name = "Enter the customer's name.";
    }

    if (!form.chqRegNo.trim()) {
        errors.chqRegNo = "Enter the CHQ registration number.";
    }

    const issued = Number(form.issuedAmount);

    if (
        !form.issuedAmount ||
        !Number.isFinite(issued) ||
        issued <= 0
    ) {
        errors.issuedAmount = "Enter an issued amount greater than zero.";
    }

    if (!form.dateIssued) {
        errors.dateIssued = "Date issued is missing.";
    }

    if (!form.bank.trim()) {
        errors.bank = "Enter the issuing bank.";
    }

    if (!form.chequeNo.trim()) {
        errors.chequeNo = "Enter the cheque number.";
    }

    if (!form.passingDate) {
        errors.passingDate = "Choose the passing date.";
    } else if (
        form.dateIssued &&
        form.passingDate < form.dateIssued
    ) {
        errors.passingDate =
            "Passing date can't be before the date issued.";
    }

    return errors;
}

